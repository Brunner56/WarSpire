export const CLASS_BY_ID = Object.fromEntries(CLASSES.map(c => [c.id, c])) as Record<ClassId, ClassDef>;

const PRIEST_RACIAL: Partial<Record<RaceId, string>> = { human: 'pr_desperate', dwarf: 'pr_fear_ward', nightelf: 'pr_starshards', undead: 'pr_plague', troll: 'pr_shadowguard' };

export function starterDeck(cls: ClassId, spec: string, race: RaceId): string[] {
  const c = CLASS_BY_ID[cls];
  const tree = c.trees.find(t => t.id === spec) ?? c.trees[0];
  const deck = [...c.base, tree.sig];
  // Feral fights in forms; Wrath would knock it out of them, so trade most Wraths for form attacks.
  if (cls === 'druid' && spec === 'feral') {
    for (let i = 0; i < 3; i++) deck.splice(deck.indexOf('d_wrath'), 1);
    deck.push('d_claw', 'd_rake', 'd_maul');
  }
  if (cls === 'priest' && PRIEST_RACIAL[race]) deck.push(PRIEST_RACIAL[race]!);
  return deck;
}
